const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('freedom', {
  getState: () => ipcRenderer.invoke('get-state'),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  onSpeak: (fn) => ipcRenderer.on('speak', (_e, text) => fn(text)),
  togglePanel: () => ipcRenderer.send('toggle-panel'),
  collapse: () => ipcRenderer.send('collapse'),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  contextMenu: () => ipcRenderer.send('context-menu'),
  setAuto: (on) => ipcRenderer.send('set-auto', on),
  setMode: (mode) => ipcRenderer.send('set-mode', mode),
  setMic: (on) => ipcRenderer.send('set-mic', on),
  setNarrative: (on) => ipcRenderer.send('set-narrative', on),
  voiceClip: (pcm, sampleRate) => ipcRenderer.send('voice-clip', { pcm, sampleRate }),
  ask: (question) => ipcRenderer.send('ask', question),
  addTask: (text) => ipcRenderer.send('task-add', text),
  removeTask: (id) => ipcRenderer.send('task-remove', id),
  toggleTask: (id) => ipcRenderer.send('task-toggle', id),
  runTask: (id) => ipcRenderer.send('task-run', id),
  stopAgent: () => ipcRenderer.send('agent-stop'),
  answerAgent: (answer) => ipcRenderer.send('agent-answer', answer),
  clear: () => ipcRenderer.send('clear'),
  saveSettings: (s) => ipcRenderer.send('save-settings', s),
  quit: () => ipcRenderer.send('quit'),
});
